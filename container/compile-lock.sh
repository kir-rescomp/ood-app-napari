#!/usr/bin/env bash
# Compile the pinned environments for the napari-spatialdata image.
#
#   ./compile-lock.sh
#
# Reads requirements.in and writes two files for the main environment:
#
#   requirements.lock        every package except PyTorch and its CUDA
#                            libraries, installed from PyPI
#   requirements-torch.txt   the torch and torchvision versions, installed
#                            from PyTorch's CPU-only index
#
# and reads requirements-cosmx.in to write requirements-cosmx.lock, for the
# separate napari-cosmx environment.
#
# The image is CPU only. PyPI's Linux build of PyTorch depends on about twenty
# NVIDIA CUDA packages (several gigabytes), which are only reached through
# torch, so they are left out of the lock and the CPU-only build of the same
# torch version is installed instead (see the definition file).
#
# Requires uv and access to pypi.org.

set -euo pipefail
cd "$(dirname "$0")"

full=$(mktemp)
trap 'rm -f "${full}"' EXIT

# overrides.txt lists the few dependency caps that are overridden, with the
# reason for each.
uv pip compile requirements.in \
    --override overrides.txt \
    --python-version 3.12 \
    --python-platform x86_64-manylinux_2_28 \
    --no-header --quiet \
    -o "${full}"

python3 - "${full}" <<'PY'
import re
import sys
from pathlib import Path

lines = Path(sys.argv[1]).read_text().splitlines(keepends=True)

# Packages that are only present because of PyPI's CUDA build of PyTorch.
cuda_only = re.compile(r"^(nvidia-[a-z0-9-]+|cuda-(bindings|pathfinder|toolkit)|triton)==")
torch_pkgs = re.compile(r"^(torch|torchvision)==")

blocks, current = [], []
for line in lines:
    if re.match(r"^[A-Za-z0-9]", line) and current:
        blocks.append(current)
        current = []
    current.append(line)
if current:
    blocks.append(current)

kept, torch, dropped = [], [], []
for block in blocks:
    head = block[0]
    if torch_pkgs.match(head):
        torch.append(head.strip())
    elif cuda_only.match(head):
        dropped.append(head.split("==")[0])
    else:
        kept.extend(block)

header = (
    "# Pinned environment for the napari-spatialdata image, generated by\n"
    "# compile-lock.sh from requirements.in. Do not edit by hand.\n"
    "# torch and torchvision are pinned in requirements-torch.txt (CPU-only\n"
    "# builds); their CUDA dependencies are deliberately absent.\n"
)
Path("requirements.lock").write_text(header + "".join(kept))
Path("requirements-torch.txt").write_text(
    "# CPU-only PyTorch for the napari-spatialdata image, generated by\n"
    "# compile-lock.sh. Installed from https://download.pytorch.org/whl/cpu\n"
    + "\n".join(torch) + "\n"
)
print(f"requirements.lock: {sum(1 for l in kept if re.match(r'^[A-Za-z0-9]', l))} packages")
print(f"requirements-torch.txt: {', '.join(torch) or 'none'}")
print(f"left out (CUDA, via torch): {len(dropped)} packages")
PY

uv pip compile requirements-cosmx.in \
    --python-version 3.12 \
    --python-platform x86_64-manylinux_2_28 \
    --no-header --quiet \
    -o requirements-cosmx.lock
sed -i '1i # Pinned environment for napari-cosmx (/opt/napari-cosmx-env), generated by\n# compile-lock.sh from requirements-cosmx.in. Do not edit by hand.' requirements-cosmx.lock
echo "requirements-cosmx.lock: $(grep -cE '^[A-Za-z0-9]' requirements-cosmx.lock) packages"
